// 仿真用的"NPU"顶层 = 矩阵单元 mvm_top + 向量单元（rtl/vpu_units.sv），端口按前缀区分。
// 上板时各单元之间改由片上调度器连接，这里先由电脑端（cocotb）逐个调度，便于逐运算比对。
/* verilator lint_off DECLFILENAME */
module npu_top (
    input  logic         aclk,
    input  logic         aresetn,
    input  logic [15:0]  s_axil_awaddr,
    input  logic         s_axil_awvalid,
    output logic         s_axil_awready,
    input  logic [31:0]  s_axil_wdata,
    input  logic [3:0]   s_axil_wstrb,
    input  logic         s_axil_wvalid,
    output logic         s_axil_wready,
    output logic [1:0]   s_axil_bresp,
    output logic         s_axil_bvalid,
    input  logic         s_axil_bready,
    input  logic [15:0]  s_axil_araddr,
    input  logic         s_axil_arvalid,
    output logic         s_axil_arready,
    output logic [31:0]  s_axil_rdata,
    output logic [1:0]   s_axil_rresp,
    output logic         s_axil_rvalid,
    input  logic         s_axil_rready,
    input  logic [255:0] s_axis_w_tdata,
    input  logic         s_axis_w_tvalid,
    output logic         s_axis_w_tready,
    output logic [31:0]  m_axis_y_tdata,
    output logic         m_axis_y_tvalid,
    input  logic         m_axis_y_tready,
    output logic         m_axis_y_tlast,
    input  logic [63:0] q_a_tdata,
    input  logic q_a_tvalid,
    input  logic q_a_tlast,
    output logic q_a_tready,
    output logic [63:0] q_y_tdata,
    output logic q_y_tvalid,
    output logic q_y_tlast,
    input  logic q_y_tready,
    output logic [7:0] q_s,
    input  logic [63:0] rms_a_tdata,
    input  logic rms_a_tvalid,
    input  logic rms_a_tlast,
    output logic rms_a_tready,
    input  logic [63:0] rms_b_tdata,
    input  logic rms_b_tvalid,
    input  logic rms_b_tlast,
    output logic rms_b_tready,
    output logic [63:0] rms_y_tdata,
    output logic rms_y_tvalid,
    output logic rms_y_tlast,
    input  logic rms_y_tready,
    input  logic [24:0] rms_recip_n,
    input  logic [63:0] sm_a_tdata,
    input  logic sm_a_tvalid,
    input  logic sm_a_tlast,
    output logic sm_a_tready,
    output logic [63:0] sm_y_tdata,
    output logic sm_y_tvalid,
    output logic sm_y_tlast,
    input  logic sm_y_tready,
    input  logic [63:0] ew_a_tdata,
    input  logic ew_a_tvalid,
    input  logic ew_a_tlast,
    output logic ew_a_tready,
    input  logic [63:0] ew_b_tdata,
    input  logic ew_b_tvalid,
    input  logic ew_b_tlast,
    output logic ew_b_tready,
    output logic [63:0] ew_y_tdata,
    output logic ew_y_tvalid,
    output logic ew_y_tlast,
    input  logic ew_y_tready,
    input  logic [0:0] ew_op,
    input  logic [63:0] rope_a_tdata,
    input  logic rope_a_tvalid,
    input  logic rope_a_tlast,
    output logic rope_a_tready,
    input  logic [63:0] rope_b_tdata,
    input  logic rope_b_tvalid,
    input  logic rope_b_tlast,
    output logic rope_b_tready,
    output logic [63:0] rope_y_tdata,
    output logic rope_y_tvalid,
    output logic rope_y_tlast,
    input  logic rope_y_tready,
    input  logic [519:0] at_r_tdata,
    input  logic at_r_tvalid,
    input  logic at_r_tlast,
    output logic at_r_tready,
    output logic [63:0] at_y_tdata,
    output logic at_y_tvalid,
    output logic at_y_tlast,
    input  logic at_y_tready,
    input  logic [16:0] at_inv_sqrt_hs,
    input  logic [7:0] at_hs
);
    mvm_top u_mvm (.*);
    vpu_quant u_quant (
        .clk(aclk),
        .rst_n(aresetn),
        .a_tdata(q_a_tdata),
        .a_tvalid(q_a_tvalid),
        .a_tlast(q_a_tlast),
        .a_tready(q_a_tready),
        .y_tdata(q_y_tdata),
        .y_tvalid(q_y_tvalid),
        .y_tlast(q_y_tlast),
        .y_tready(q_y_tready),
        .s_out(q_s)
    );
    vpu_rmsnorm u_rms (
        .clk(aclk),
        .rst_n(aresetn),
        .a_tdata(rms_a_tdata),
        .a_tvalid(rms_a_tvalid),
        .a_tlast(rms_a_tlast),
        .a_tready(rms_a_tready),
        .b_tdata(rms_b_tdata),
        .b_tvalid(rms_b_tvalid),
        .b_tlast(rms_b_tlast),
        .b_tready(rms_b_tready),
        .y_tdata(rms_y_tdata),
        .y_tvalid(rms_y_tvalid),
        .y_tlast(rms_y_tlast),
        .y_tready(rms_y_tready),
        .recip_n(rms_recip_n)
    );
    vpu_softmax u_sm (
        .clk(aclk),
        .rst_n(aresetn),
        .a_tdata(sm_a_tdata),
        .a_tvalid(sm_a_tvalid),
        .a_tlast(sm_a_tlast),
        .a_tready(sm_a_tready),
        .y_tdata(sm_y_tdata),
        .y_tvalid(sm_y_tvalid),
        .y_tlast(sm_y_tlast),
        .y_tready(sm_y_tready)
    );
    vpu_ew u_ew (
        .clk(aclk),
        .rst_n(aresetn),
        .a_tdata(ew_a_tdata),
        .a_tvalid(ew_a_tvalid),
        .a_tlast(ew_a_tlast),
        .a_tready(ew_a_tready),
        .b_tdata(ew_b_tdata),
        .b_tvalid(ew_b_tvalid),
        .b_tlast(ew_b_tlast),
        .b_tready(ew_b_tready),
        .y_tdata(ew_y_tdata),
        .y_tvalid(ew_y_tvalid),
        .y_tlast(ew_y_tlast),
        .y_tready(ew_y_tready),
        .op(ew_op)
    );
    vpu_rope u_rope (
        .clk(aclk),
        .rst_n(aresetn),
        .a_tdata(rope_a_tdata),
        .a_tvalid(rope_a_tvalid),
        .a_tlast(rope_a_tlast),
        .a_tready(rope_a_tready),
        .b_tdata(rope_b_tdata),
        .b_tvalid(rope_b_tvalid),
        .b_tlast(rope_b_tlast),
        .b_tready(rope_b_tready),
        .y_tdata(rope_y_tdata),
        .y_tvalid(rope_y_tvalid),
        .y_tlast(rope_y_tlast),
        .y_tready(rope_y_tready)
    );
    attn_head u_attn (
        .clk(aclk),
        .rst_n(aresetn),
        .r_tdata(at_r_tdata),
        .r_tvalid(at_r_tvalid),
        .r_tlast(at_r_tlast),
        .r_tready(at_r_tready),
        .y_tdata(at_y_tdata),
        .y_tvalid(at_y_tvalid),
        .y_tlast(at_y_tlast),
        .y_tready(at_y_tready),
        .inv_sqrt_hs(at_inv_sqrt_hs),
        .hs(at_hs)
    );
endmodule
